export type Locale = 'en' | 'vi';
const catalogs: Record<Locale, Record<MessageKey, string>> = { en, vi };

export function resolveLocale(pref: LocalePref, browserLanguage = typeof navigator === 'undefined' ? 'en' : navigator.language): Locale {
  if (pref === 'en' || pref === 'vi') return pref;
  return browserLanguage.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const catalog = catalogs[locale];
  return (key, vars) => {
    const template = catalog[key] ?? en[key] ?? key;
    return vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match)) : template;
  };
}

export function hasMessage(key: string): key is MessageKey {
  return key in en;
}

export const I18nContext = createContext<{ t: Translate; locale: Locale }>({ t: translator('en'), locale: 'en' });
export const useI18n = () => useContext(I18nContext);

/** Localized text for an error code; unknown codes show a generic message with the code. */
export function errorText(t: Translate, code: string, retryAfterSeconds?: number): string {
  const key = `error.${code}`;
  if (hasMessage(key)) return t(key, { seconds: retryAfterSeconds ?? 30 });
  return t('error.generic', { code });
}
